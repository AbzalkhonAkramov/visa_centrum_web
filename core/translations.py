def format_slots(n, lang):
    """Localized '<n> openings'-style label for a vacancy's slot count."""
    if lang == "ru":
        rem100 = n % 100
        rem10 = n % 10
        if 11 <= rem100 <= 14:
            word = "мест"
        elif rem10 == 1:
            word = "место"
        elif 2 <= rem10 <= 4:
            word = "места"
        else:
            word = "мест"
        return f"{n} {word}"
    if lang == "de":
        return f"{n} " + ("Stelle" if n == 1 else "Stellen")
    if lang == "en":
        return f"{n} " + ("opening" if n == 1 else "openings")
    return f"{n} ta o'rin"
